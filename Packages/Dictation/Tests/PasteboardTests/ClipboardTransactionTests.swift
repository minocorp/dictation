import Clocks
import ConcurrencyExtras
import CoreTesting
import Foundation
@testable import Pasteboard
import Synchronization
import Testing

private typealias ManualClock = Clocks.TestClock<Duration>

internal struct ClipboardTransactionTests {
    private let original = [
        PasteboardItem.plain("original"),
        PasteboardItem(representations: ["public.png": Data([1, 2, 3]), "public.tiff": Data([4])]),
    ]

    private let pasteboard: FakePasteboard

    init() {
        pasteboard = FakePasteboard(items: original)
    }

    @Test
    func writesTextWithTransientAutoGeneratedAndSessionMarkers() async {
        let transaction = makeTransaction(clock: ImmediateClock<Duration>())
        let written = Mutex<[String: Data]>([:])
        let board = pasteboard
        await transaction.pasting("hello") {
            written.withLock { $0 = board.currentItems.first?.representations ?? [:] }
        }
        let types = written.withLock { Set($0.keys) }
        #expect(types.contains(PasteboardType.transient))
        #expect(types.contains(PasteboardType.autoGenerated))
        #expect(types.contains(PasteboardType.session))
        #expect(written.withLock { $0[PasteboardType.plainText] } == Data("hello".utf8))
    }

    @Test
    func restoresEveryItemAndTypeWhenStillOurs() async {
        let transaction = makeTransaction(clock: ImmediateClock<Duration>())
        await transaction.pasting("hello") {}
        await transaction.settle()
        #expect(pasteboard.currentItems == original)
    }

    @Test
    func restoresAnEmptyPasteboardByClearingIt() async {
        let empty = FakePasteboard()
        let transaction = ClipboardTransaction(
            pasteboard: empty,
            clock: ImmediateClock<Duration>(),
        )
        await transaction.pasting("hello") {}
        await transaction.settle()
        #expect(empty.currentItems.isEmpty)
    }

    @Test
    func keepsACopyTheUserMadeDuringThePaste() async {
        let transaction = makeTransaction(clock: ImmediateClock<Duration>())
        let board = pasteboard
        await transaction.pasting("hello") { board.userCopies("user copy") }
        await transaction.settle()
        #expect(pasteboard.plainText == "user copy")
    }

    @Test
    func backToBackSessionsRestoreTheOriginalClipboardOnce() async {
        let clock = ManualClock()
        let transaction = makeTransaction(clock: clock)
        await transaction.pasting("first") {}
        await transaction.pasting("second") {}
        #expect(pasteboard.plainText == "second")
        await finishRestoreWindow(clock: clock, transaction: transaction)
        #expect(pasteboard.currentItems == original)
    }

    @Test
    func secondSessionNeverSnapshotsTheFirstSessionsText() async {
        let clock = ManualClock()
        let transaction = makeTransaction(clock: clock)
        await transaction.pasting("first") {}
        await transaction.pasting("second") {}
        await finishRestoreWindow(clock: clock, transaction: transaction)
        #expect(pasteboard.plainText == "original")
    }

    @Test
    func userCopyBetweenSessionsBecomesTheNextBaseline() async {
        let clock = ManualClock()
        let transaction = makeTransaction(clock: clock)
        await transaction.pasting("first") {}
        pasteboard.userCopies("user copy")
        await transaction.pasting("second") {}
        await finishRestoreWindow(clock: clock, transaction: transaction)
        #expect(pasteboard.plainText == "user copy")
    }

    @Test
    func neverRunsTwoSessionsAtOnce() async {
        let transaction = makeTransaction(clock: ImmediateClock<Duration>())
        let running = Mutex(0)
        let maximum = Mutex(0)
        await withTaskGroup(of: Void.self) { group in
            for index in 0..<8 {
                group.addTask {
                    await transaction.pasting("text \(index)") {
                        let now = running.withLock { value -> Int in
                            value += 1
                            return value
                        }
                        maximum.withLock { $0 = max($0, now) }
                        await Task.yield()
                        running.withLock { $0 -= 1 }
                    }
                }
            }
        }
        #expect(maximum.withLock { $0 } == 1)
    }

    @Test
    func copyWritesTransientTextWithoutASessionMarker() async {
        let transaction = makeTransaction(clock: ImmediateClock<Duration>())
        await transaction.copy("kept")
        let types = Set(pasteboard.currentItems.flatMap { $0.representations.keys })
        #expect(pasteboard.plainText == "kept")
        #expect(types.contains(PasteboardType.transient))
        #expect(!types.contains(PasteboardType.session))
    }

    @Test
    func copyCancelsThePendingRestore() async {
        let clock = ManualClock()
        let transaction = makeTransaction(clock: clock)
        await transaction.pasting("first") {}
        await transaction.copy("kept")
        await finishRestoreWindow(clock: clock, transaction: transaction)
        #expect(pasteboard.plainText == "kept")
    }

    private func makeTransaction(clock: any Clock<Duration>) -> ClipboardTransaction {
        ClipboardTransaction(pasteboard: pasteboard, clock: clock)
    }

    private func finishRestoreWindow(clock: ManualClock, transaction: ClipboardTransaction) async {
        await Task.megaYield()
        await clock.advance(by: ClipboardTransaction.restoreDelay)
        await transaction.settle()
    }
}
