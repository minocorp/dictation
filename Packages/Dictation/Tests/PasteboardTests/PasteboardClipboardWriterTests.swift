import Clocks
import CoreTesting
@testable import Pasteboard
import Testing

internal struct PasteboardClipboardWriterTests {
    @Test
    func copyTransientPutsTheTextOnTheClipboardWithTransientMarkers() async {
        let board = FakePasteboard(items: [.plain("original")])
        let transaction = ClipboardTransaction(
            pasteboard: board,
            clock: ImmediateClock<Duration>(),
        )
        await PasteboardClipboardWriter(transaction: transaction).copyTransient("kept")
        let types = Set(board.currentItems.flatMap { $0.representations.keys })
        #expect(board.plainText == "kept")
        #expect(types.contains(PasteboardType.transient))
        #expect(types.contains(PasteboardType.autoGenerated))
    }
}
