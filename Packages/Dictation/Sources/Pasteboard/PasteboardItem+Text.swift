import Foundation

extension PasteboardItem {
    package static func transientText(_ text: String, session: String?) -> PasteboardItem {
        var representations: [String: Data] = [
            PasteboardType.plainText: Data(text.utf8),
            PasteboardType.transient: Data(),
            PasteboardType.autoGenerated: Data(),
        ]
        if let session {
            representations[PasteboardType.session] = Data(session.utf8)
        }
        return PasteboardItem(representations: representations)
    }
}
